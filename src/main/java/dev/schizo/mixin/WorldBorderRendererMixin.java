package dev.schizo.mixin;

import dev.schizo.client.ClientContext;
import dev.schizo.client.modules.render.NoRenderModule;
import net.minecraft.client.renderer.WorldBorderRenderer;
import net.minecraft.client.renderer.state.WorldBorderRenderState;
import net.minecraft.world.phys.Vec3;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(WorldBorderRenderer.class)
public class WorldBorderRendererMixin {

   @Inject(method = "render", at = @At("HEAD"), cancellable = true)
   private void suppressWorldBorder(
      WorldBorderRenderState borderState, Vec3 cameraPosition, double ignoredRenderDouble1, double ignoredRenderDouble2, CallbackInfo callback
   ) {
      if (schizo$noRenderModule().isToggled()
         && schizo$noRenderModule().worldBorderSetting.getValue()) {
         callback.cancel();
      }
   }

   @org.spongepowered.asm.mixin.Unique
   private static NoRenderModule schizo$noRenderModule() {
      return dev.schizo.client.bootstrap.MixinModuleRegistry.require(NoRenderModule.class);
   }
}
